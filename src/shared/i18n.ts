const dictionaries: Record<AppLanguage, Dictionary> = { en, vi, ja };

export function isAppLanguage(value: unknown): value is AppLanguage {
  return value === "en" || value === "vi" || value === "ja";
}

export function localeTag(language: AppLanguage): string {
  return language === "vi" ? "vi-VN" : language === "ja" ? "ja-JP" : "en-US";
}

export function translate(language: AppLanguage, key: TranslationKey, values: Record<string, string | number> = {}): string {
  return dictionaries[language][key].replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(values[name] ?? ""));
}
